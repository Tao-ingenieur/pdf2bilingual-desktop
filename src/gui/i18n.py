def translate(text, language='zh'):
    if language == 'zh':
        return text
    if text in EN:
        return EN[text]
    for pattern, replacement in PATTERNS:
        match = re.fullmatch(pattern, text, re.S)
        if match:
            return replacement(match)
    return text
